# This program uses list slicing to display
# different parts of a list.

planets = ["mercury", "venus", "earth", "mars", "jupiter",
           "saturn", "uranus", "neptune", "pluto"]

# Print the first three planets in the list.
print(planets[:3])

# Print the planets from index 1 up to (but not including) index 4.
print(planets[1:4])

# Print all planets starting from index 4 to the end of the list.
print(planets[4:])
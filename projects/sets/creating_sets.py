# creat an empty set

set1 = set()
print(set1)

# creating set with data

set2 = {'green', 'yellow', 'red'}
print(set2)

# create a set from a list

numbers = [1, 2, 3, 3, 4, 4]
numbers = set(numbers)
print(numbers)

# from another collection

colors = ["red", "green", "blue"]
colors = set(colors)
print(colors)